import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createApp } from '../server/app.js';

test('photography workflow: auth, upload, edit, publish, persist, unpublish, delete', async t => {
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'photo-test-'));
  let server;
  t.after(async()=>{if(server)await new Promise(r=>server.close(r));await fs.rm(dir,{recursive:true,force:true});});
  const start=async()=>{server=createApp({dataDir:dir}).listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));return `http://127.0.0.1:${server.address().port}`;};
  let base=await start();let cookie='';
  const req=async(url,options={})=>fetch(base+url,{...options,headers:{...(cookie?{cookie}:{}),...options.headers}});
  const json=(url,data,method='POST')=>req(url,{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});
  assert.equal((await req('/api/admin/content')).status,401);
  assert.equal((await json('/api/login',{password:'wrong'})).status,401);
  const password=(await fs.readFile(path.join(dir,'admin-initial-password.txt'),'utf8')).trim();
  const login=async()=>{const res=await json('/api/login',{password});assert.equal(res.status,200);cookie=res.headers.get('set-cookie').split(';')[0];};
  await login();
  assert.equal((await req('/api/admin/content')).status,200);
  assert.equal((await json('/api/categories',{name:'旅行'})).status,201);
  assert.equal((await json('/api/categories',{name:'旅行'})).status,409);
  const makeForm=(file)=>{const f=new FormData();f.set('title','晨光');f.set('category','旅行');f.set('description','清晨的记录');f.set('published','false');f.set('photo',file,'photo.png');return f;};
  assert.equal((await req('/api/works',{method:'POST',body:makeForm(new Blob(['<svg></svg>'],{type:'image/png'}))})).status,400);
  const png=new Blob([Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jA1sAAAAASUVORK5CYII=','base64')],{type:'image/png'});
  const uploaded=await req('/api/works',{method:'POST',body:makeForm(png)});assert.equal(uploaded.status,201);const work=await uploaded.json();
  assert.equal((await req('/api/content').then(r=>r.json())).works.length,0);
  assert.equal((await req('/media/'+work.filename)).status,200);
  const savedCookie=cookie;cookie='';assert.equal((await req('/media/'+work.filename)).status,404);cookie=savedCookie;
  assert.equal((await req('/api/categories/'+encodeURIComponent('旅行'),{method:'DELETE'})).status,409);
  assert.equal((await json('/api/works/'+work.id,{title:'晨光 · 修订',description:'新的简介',category:'旅行',published:true},'PATCH')).status,200);
  assert.equal((await req('/api/content').then(r=>r.json())).works[0].title,'晨光 · 修订');
  cookie='';assert.equal((await req('/media/'+work.filename)).status,200);
  await new Promise(r=>server.close(r));base=await start();
  assert.equal((await req('/api/content').then(r=>r.json())).works.length,1);
  await login();
  assert.equal((await json('/api/categories',{name:'blocked'} ,'POST').then(r=>r.status)),201);
  assert.equal((await req('/api/categories',{method:'POST',headers:{origin:'https://evil.example','Content-Type':'application/json'},body:JSON.stringify({name:'attack'})})).status,403);
  assert.equal((await json('/api/works/'+work.id,{...work,published:false},'PATCH')).status,200);
  cookie='';assert.equal((await req('/media/'+work.filename)).status,404);assert.equal((await req('/api/content').then(r=>r.json())).works.length,0);
  await login();assert.equal((await req('/api/works/'+work.id,{method:'DELETE'})).status,200);
  await assert.rejects(fs.stat(path.join(dir,'uploads',work.filename)));
  assert.equal((await req('/api/categories/'+encodeURIComponent('旅行'),{method:'DELETE'})).status,200);
  assert.equal((await json('/api/logout',{})).status,200);assert.equal((await req('/api/admin/content')).status,401);
});
